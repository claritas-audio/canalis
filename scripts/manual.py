#!/usr/bin/env python3
"""Keeps the manual's navigation in step with its pages, as the website shows them.

`docs/manual/README.md` lists the pages in order; this script rewrites that list with each
page's one-sentence intro, and the "Previous · Contents · Next" line at the end of every
page. Run it after adding, removing, renaming or reordering a page:

    python3 scripts/manual.py           # rewrite
    python3 scripts/manual.py --check   # exit 1 if anything is out of date
"""

import re
import sys
from pathlib import Path

MANUAL = Path(__file__).resolve().parent.parent / "docs" / "manual"
NAV = "<!-- nav: generated by scripts/manual.py -->"
ENTRY = re.compile(r"^\d+\. \[[^\]]+\]\(([\w-]+)\.md\)", re.M)


def title_and_intro(text: str) -> tuple[str, str]:
    title = re.search(r"^# (.+)$", text, re.M).group(1)
    after = text.split(f"# {title}\n", 1)[1].strip().split("\n\n", 1)[0]
    # The first sentence: the one the site uses as the page description too.
    return title, re.split(r"(?<=\.)\s", " ".join(after.split()))[0]


def main() -> int:
    index_path = MANUAL / "README.md"
    index = index_path.read_text()
    slugs = ENTRY.findall(index)
    pages = {s: (MANUAL / f"{s}.md").read_text() for s in slugs}
    info = {s: title_and_intro(t) for s, t in pages.items()}

    head = index[: ENTRY.search(index).start()]
    listing = "\n".join(
        f"{i}. [{info[s][0]}]({s}.md): {info[s][1]}" for i, s in enumerate(slugs, 1)
    )
    wanted = {index_path: f"{head}{listing}\n"}

    for i, slug in enumerate(slugs):
        prev = f"← [{info[slugs[i - 1]][0]}]({slugs[i - 1]}.md)" if i > 0 else ""
        nxt = f"[{info[slugs[i + 1]][0]}]({slugs[i + 1]}.md) →" if i + 1 < len(slugs) else ""
        line = " · ".join(p for p in (prev, "[Contents](README.md)", nxt) if p)
        body = pages[slug].split(f"\n{NAV}", 1)[0].rstrip("\n")
        wanted[MANUAL / f"{slug}.md"] = f"{body}\n\n{NAV}\n\n---\n\n{line}\n"

    stale = [p for p, text in wanted.items() if p.read_text() != text]
    if "--check" in sys.argv:
        for p in stale:
            print(f"out of date: {p.relative_to(MANUAL.parent.parent)}")
        return 1 if stale else 0
    for p in stale:
        p.write_text(wanted[p])
    print(f"{len(stale)} file(s) updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
